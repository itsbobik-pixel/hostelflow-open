// Builds the public legal pages from their texts in docs/legal/:
//   privacy.md -> public/privacy.html (hostelflow.it/privacy)
//   terms.md   -> public/terms.html   (hostelflow.it/terms)
// The .md files stay the one place to edit. Run: npm run build:legal
//
// Only the bits of Markdown those files use: headings, paragraphs, lists,
// tables, **bold** and `code`. A `[PLACEHOLDER]` in backticks shows up
// highlighted on the page, and the script lists the ones still left.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const PAGES = { privacy: 'privacy.md', terms: 'terms.md' };

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function inline(s) {
  return esc(s)
    .replace(/`([^`]+)`/g, (_, c) => (/^\[.*\]$/.test(c) ? `<mark>${c}</mark>` : `<code>${c}</code>`))
    .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
    .replace(/\*(.+?)\*/g, '<i>$1</i>')
    .replace(/\b([\w.+-]+@[\w-]+\.[\w.]+\w)/g, '<a href="mailto:$1">$1</a>')
    .replace(/\b(garanteprivacy\.it)\b/g, '<a href="https://www.garanteprivacy.it" rel="noopener">$1</a>');
}

const slug = s => s.toLowerCase().normalize('NFD').replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-');

// Markdown lines -> HTML, one block at a time.
function blocks(lines, prefix) {
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim() || line.trim() === '---') { i++; continue; }
    const h = line.match(/^(#{2,4}) (.*)$/);
    if (h) {
      const level = h[1].length; // ## -> h2 on the page, ### -> h3
      out.push(`<h${level} id="${prefix}-${slug(h[2])}">${inline(h[2])}</h${level}>`);
      i++;
      continue;
    }
    if (line.startsWith('|')) {
      const rows = [];
      while (i < lines.length && lines[i].startsWith('|')) rows.push(lines[i++]);
      const cells = r => r.slice(1, -1).split('|').map(c => inline(c.trim()));
      const [head, , ...body] = rows;
      out.push('<div class="table"><table>',
        `<thead><tr>${cells(head).map(c => `<th>${c}</th>`).join('')}</tr></thead>`,
        `<tbody>${body.map(r => `<tr>${cells(r).map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody>`,
        '</table></div>');
      continue;
    }
    const item = /^(- |\d+\. )/;
    if (item.test(line)) {
      const ordered = /^\d/.test(line);
      const items = [];
      while (i < lines.length && lines[i].trim()) {
        if (item.test(lines[i])) items.push(lines[i].replace(item, ''));
        else items[items.length - 1] += ' ' + lines[i].trim(); // continuation line
        i++;
      }
      const tag = ordered ? 'ol' : 'ul';
      out.push(`<${tag}>${items.map(t => `<li>${inline(t)}</li>`).join('')}</${tag}>`);
      continue;
    }
    const para = [];
    while (i < lines.length && lines[i].trim() && !/^(#|\||- |\d+\. |---)/.test(lines[i])) para.push(lines[i++].trim());
    out.push(`<p>${inline(para.join(' '))}</p>`);
  }
  return out.join('\n');
}

// The file: "# IT title / EN title", a draft note, then "## Italiano",
// "## English" and optionally an annex in each language.
export function renderLegal(md, page) {
  md = md.replace(/\r\n?/g, '\n'); // Windows checkouts have CRLF line ends
  const lines = md.split('\n');
  const [titleIt, titleEn] = lines[0].replace(/^# HostelFlow — /, '').split(' / ');
  const parts = { it: [], en: [] };
  let lang = null;
  for (const line of lines) {
    if (/^## (Italiano|Allegato)/.test(line)) lang = 'it';
    else if (/^## (English|Annex)/.test(line)) lang = 'en';
    if (!lang) continue; // title and draft note
    if (/^## (Italiano|English)$/.test(line)) continue;
    parts[lang].push(line);
  }
  const other = page === 'privacy'
    ? { href: '/terms', it: 'Termini di servizio', en: 'Terms of Service' }
    : { href: '/privacy', it: 'Informativa sulla privacy', en: 'Privacy Policy' };
  const placeholders = [...new Set(md.split('\n').slice(lines.findIndex(l => l.startsWith('## ')))
    .join('\n').match(/`\[[^\]`]+\]`/g) || [])];
  return { placeholders, html: `<!doctype html>
<html lang="it" class="it">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(titleIt)} — HostelFlow</title>
<meta name="description" content="HostelFlow: ${esc(titleIt)} / ${esc(titleEn)}.">
<meta name="theme-color" content="#1f2433">
<link rel="canonical" href="https://hostelflow.it/${page}">
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<link rel="stylesheet" href="/landing.css">
<script src="/landing.js" defer></script>
</head>
<body>
<!-- Generated by scripts/build-legal.mjs from docs/legal/${PAGES[page]} — edit that file, then npm run build:legal. -->

<header class="nav" id="nav">
  <div class="wrap nav-in">
    <a class="brand" href="/" aria-label="HostelFlow">
      <svg class="mark" viewBox="0 0 512 512" aria-hidden="true"><rect width="512" height="512" rx="120"/><path d="M176 112v288M176 290c0-60 36-92 80-92s80 32 80 92v34c0 44 30 70 70 56"/></svg>
      <span>hostel<b>flow</b></span>
    </a>
    <div class="nav-right">
      <button type="button" class="lang" id="lang" aria-label="Lingua / Language"><span class="it">EN</span><span class="en">IT</span></button>
      <a class="signin" href="/app"><span class="it">Accedi</span><span class="en">Sign in</span></a>
    </div>
  </div>
</header>

<main class="legal wrap">
<section class="it" lang="it">
<h1>${esc(titleIt)}</h1>
${blocks(parts.it, 'it')}
</section>
<section class="en" lang="en">
<h1>${esc(titleEn)}</h1>
${blocks(parts.en, 'en')}
</section>
</main>

<footer class="foot">
  <div class="wrap foot-in">
    <a class="brand" href="/" aria-label="HostelFlow">
      <svg class="mark" viewBox="0 0 512 512" aria-hidden="true"><rect width="512" height="512" rx="120"/><path d="M176 112v288M176 290c0-60 36-92 80-92s80 32 80 92v34c0 44 30 70 70 56"/></svg>
      <span>hostel<b>flow</b></span>
    </a>
    <div class="foot-links">
      <a href="mailto:support@hostelflow.it">support@hostelflow.it</a>
      <a href="${other.href}"><span class="it">${other.it}</span><span class="en">${other.en}</span></a>
    </div>
    <p class="copy">© 2026 HostelFlow</p>
  </div>
</footer>
</body>
</html>
` };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [page, file] of Object.entries(PAGES)) {
    const md = readFileSync(new URL(`../docs/legal/${file}`, import.meta.url), 'utf8');
    const { html, placeholders } = renderLegal(md, page);
    writeFileSync(new URL(`../public/${page}.html`, import.meta.url), html);
    console.log(`public/${page}.html` + (placeholders.length ? ` — still to fill in: ${placeholders.join(', ')}` : ''));
  }
}
