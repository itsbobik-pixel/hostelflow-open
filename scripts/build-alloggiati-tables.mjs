// Regenerates src/registration/it/alloggiati-tables.js from the official Alloggiati Web code
// tables (public download, no login needed):
//   https://alloggiatiweb.poliziadistato.it/portalealloggiati/Tabelle.aspx
//
// Run from the repo root:  npm run build:tables
// Only entries that are still valid (empty DataFineVal) are kept.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const BASE = 'https://alloggiatiweb.poliziadistato.it/portalealloggiati/ashx/Download.ashx';

async function fetchCsv(id, name) {
  const res = await fetch(`${BASE}?ID=${id}&N=${name}`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const lines = (await res.text()).split(/\r?\n/).filter(l => l.trim());
  lines.shift(); // header
  // No field contains a comma except possibly the description, and the
  // description is always the 2nd column — so split off the ends instead.
  return lines.map(l => {
    const parts = l.split(',');
    const code = parts[0].trim();
    if (parts.length <= 2) return { code, name: parts.slice(1).join(',').trim() };
    const end = parts[parts.length - 1].trim();
    const prov = parts[parts.length - 2].trim();
    const name = parts.slice(1, parts.length - 2).join(',').trim();
    return { code, name, prov, end };
  });
}

const stati = (await fetchCsv(1, 'STATI')).filter(r => !r.end);
const comuni = (await fetchCsv(0, 'COMUNI')).filter(r => !r.end);
const documenti = await fetchCsv(2, 'DOCUMENTI');
const tipi = await fetchCsv(3, 'TIPO_ALLOGGIATO');

const out = `// GENERATED by scripts/build-alloggiati-tables.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
// Source: official Alloggiati Web code tables (Polizia di Stato), valid entries only.

// Stati: code -> name
export const STATI = ${JSON.stringify(Object.fromEntries(stati.map(r => [r.code, r.name])))};

// Comuni: "NAME|PROV" -> code
export const COMUNI = ${JSON.stringify(Object.fromEntries(comuni.map(r => [`${r.name}|${r.prov}`, r.code])))};

// Tipi documento: code -> name
export const DOCUMENTI = ${JSON.stringify(Object.fromEntries(documenti.map(r => [r.code, r.name])))};

// Tipi alloggiato: code -> name
export const TIPI_ALLOGGIATO = ${JSON.stringify(Object.fromEntries(tipi.map(r => [r.code, r.name])))};
`;

writeFileSync(fileURLToPath(new URL('../src/registration/it/alloggiati-tables.js', import.meta.url)), out);
console.log(`stati ${stati.length}, comuni ${comuni.length}, documenti ${documenti.length}, tipi ${tipi.length}`);
