function t(s, vars) {
  let out = (DICT && DICT[s]) || s;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return out;
}

function tx(message) {
  if (!DICT || typeof message !== 'string' || !message) return message;
  if (DICT[message]) return DICT[message];
  for (const [re, rep] of PATTERNS) if (re.test(message)) return message.replace(re, rep);
  return message;
}

// Translates the fixed text of the page (labels, buttons, placeholders).
function translateStatic(root = document.body) {
  if (!DICT) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node; (node = walker.nextNode());) {
    const s = node.nodeValue.trim();
    if (s && DICT[s]) node.nodeValue = node.nodeValue.replace(s, DICT[s]);
  }
  for (const el of root.querySelectorAll('[placeholder], [aria-label], [alt], [title]')) {
    for (const attr of ['placeholder', 'aria-label', 'alt', 'title']) {
      const v = el.getAttribute(attr);
      if (v && DICT[v]) el.setAttribute(attr, DICT[v]);
    }
  }
}
